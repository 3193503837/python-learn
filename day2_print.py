# ---- 1. print() 输出多段内容 ----
# 用逗号隔开多个内容，print 会自动用空格连接它们

print("我叫小明", "今年20岁", "来自北京")
# 输出：我叫小明 今年20岁 来自北京

# 可以混合不同类型的内容（文字和数字）
print("年龄：", 20, "岁")
# 输出：年龄： 20 岁


# ---- 2. end 参数：控制 print 结束时加什么 ----
# 默认情况下，print() 输出完会自动换行
# 用 end= 可以改变这个行为

print("第一行", end=" ")   # 结束时不加换行，加一个空格
print("第二行")            # 所以这行会接在上一行后面
# 输出：第一行 第二行

print("Hello", end="")    # 结束时什么都不加
print("Python")
# 输出：HelloPython

print("第一", end="→")    # 结束时加箭头
print("第二", end="→")
print("第三")
# 输出：第一→第二→第三


# ---- 3. sep 参数：控制多个内容之间的分隔符 ----
# 默认分隔符是空格，用 sep= 可以改变

print("苹果", "香蕉", "橘子", sep=", ")
# 输出：苹果, 香蕉, 橘子

print("2026", "09", "19", sep="-")
# 输出：2026-09-19

print("用户名", "密码", sep=" | ")
# 输出：用户名 | 密码


# ---- 4. 注释的用法 ----
# 单行注释：用 # 开头，Python 不会执行
# 注释是写给人看的，可以解释代码在做什么

# 注释可以写在代码上面
print("Hello")  # 也可以写在代码右边

# 好的注释应该解释"为什么"，而不是"做什么"
# 比如：# 计算总价 = 单价 * 数量  ← 这是不好的注释（代码本身已经说明了）
# 比如：# 价格不含税，需要额外加13%增值税  ← 这是好的注释


# ---- 5. 代码缩进 ----
# Python 对缩进（空格）非常敏感
# 同一级的代码必须对齐，缩进代表代码的"层级"
#
# 规则：
#   - 用 4 个空格缩进（推荐）
#   - 同一层级的代码缩进要一样
#   - 遇到冒号 : 后面的代码要缩进
#
# 先有个印象就行，下周学 if 判断时会深入练习
# 今天先知道：Python 很在意空格对齐！


# ============================================
#  Day 2 小结
# ============================================
#  1. print("A", "B", "C")  → 多个内容用逗号，自动加空格
#  2. print(..., end="")    → 不换行
#  3. print(..., sep="-")   → 自定义分隔符
#  4. # 注释                → 给人看的说明，不执行
#  5. 缩进很重要            → 同一层级对齐，用4个空格
