# ---------- 第5题：温度转换器（小挑战） ----------
# 定义变量 celsius = 30 （摄氏温度）
# 摄氏转华氏公式：华氏 = 摄氏 × 9/5 + 32
# 计算出华氏温度，存在变量 fahrenheit 中
# 输出："XX摄氏度 = XX华氏度"
#
# 提示：直接用变量做数学运算就行
# fahrenheit = celsius * 9 / 5 + 32

# 你的代码写在这里：
celsius=30
fahrenheit=celsius*9/5+32
print(f"{celsius}摄氏度={fahrenheit}华氏度")



