# ---------- 第4题：类型转换 ----------
# 完成以下类型转换：
#   1. 把字符串 "456" 转成整数，存在变量 num1 中，输出 num1 和它的类型
#   2. 把整数 789 转成字符串，存在变量 s1 中，输出 s1 和它的类型
