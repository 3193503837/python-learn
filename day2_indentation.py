# ============================================
# Python 代码缩进详解
# ============================================
# 缩进就是"代码前面的空格"
# Python 用缩进来表示代码的"层级关系"
# 这是 Python 最特别的地方，也是新手最容易踩坑的地方

# ============================================
#  例子1：没有缩进（所有代码同一层级）
# ============================================

print("=== 例子1：同一层级 ===")
print("第一行")
print("第二行")
print("第三行")
# 这三行前面都没有空格，属于同一层级，按顺序从上到下执行


# ============================================
#  例子2：有缩进的代码（if 判断）
# ============================================

print("\n=== 例子2：if 判断的缩进 ===")

age = 20

if age >= 18:
    # 这里缩进了4个空格！
    # 意思是：只有 age >= 18 成立时，才执行下面缩进的代码
    print("你已经成年了")
    print("可以考驾照了")
    print("可以投票了")

# 这里没有缩进，不管条件成不成立都会执行
print("程序结束")

# 运行结果：
# 你已经成年了
# 可以考驾照了
# 可以投票了
# 程序结束

# 如果把 age 改成 15，那三行缩进的 print 都不会执行
# 只会输出：程序结束


# ============================================
#  例子3：多层缩进（if 嵌套）
# ============================================

print("\n=== 例子3：多层缩进 ===")

score = 95

if score >= 60:
    print("及格了")       # 第1层缩进：属于 if score >= 60
    if score >= 90:
        print("优秀！")    # 第2层缩进：属于 if score >= 90
        print("继续保持")  # 第2层缩进
    print("继续加油")       # 第1层缩进：属于外层 if


