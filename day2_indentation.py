# ============================================
#  缩进规则总结
# ============================================
#
#  1. 冒号 : 后面的代码必须缩进
#     比如 if xxx:  for xxx:  def xxx:
#
#  2. 同一层级的代码，缩进必须一样多
#     （就像同一班级的学生，座位要对齐）
#
#  3. 缩进用 4 个空格（标准写法）
#     不要用 Tab 键，不要用2个空格
#
#  4. 没有缩进的代码是"最外层"，从上到下依次执行
#
#  5. 缩进越多，层级越深，执行条件越严格
#
# ============================================

print("\n=== 缩进规则记忆口诀 ===")
print("遇到冒号，下一行缩进")
print("同一层级，空格要对齐")
print("四个空格，标准又好看")
