# ---- 第1题：输出自我介绍 ----
# 要求：用3行 print() 输出你的自我介绍
# 第1行：你的名字
# 第2行：你的年龄
# 第3行：你来自哪个城市
#
# 提示：每条 print() 输出一行
# 你的代码写在这里：
print("我叫邓建杰")
print("我今年十八岁")
print("我来自广东省")
# ---- 第2题：输出一句古诗 ----
# 要求：用2条 print() 分别输出诗句的两句
# 第1行：床前明月光
# 第2行：疑是地上霜
#
# 提示：每条 print() 输出一句
# 你的代码写在这里：
print("窗前地上霜")
print("疑似地上霜")

# ---- 第3题：用逗号输出多个信息 ----
# 要求：只用1条 print() 输出以下内容（用逗号隔开）
# 你的名字、你的爱好、你的星座
# 输出效果参考：小明 打篮球 天蝎座
#
# 提示：print("A", "B", "C")  逗号会自动加空格
# 你的代码写在这里：
print("我叫邓建杰","我喜欢运动","我是天蝎座")


# ---- 第4题：输出一个三角形 ----
# 要求：用3条 print() 输出以下图形（每行用星号 * 组成）
#   *
#  ***
# *****
#
# 提示：每条 print() 输出一行，注意前面的空格
# 你的代码写在这里：
print("  *")
print(" ***")
print("*****")


# ---- 第5题（挑战题）：输出一张"名片" ----
# 要求：用多条 print() 输出一张简单的名片，格式如下：
# +-----------------+
# | 姓名：XXX       |
# | 年龄：XX        |
# | 城市：XXX       |
# +-----------------+
#
# 提示：每行用 print() 输出，竖线 | 和横线 --- 都是普通字符串
# 你的代码写在这里：
print("+-----------------+")
print("| 姓名：邓建杰     |")
print("| 年龄：十八       |")
print("| 城市：广东省     |")
print("+-----------------+")



