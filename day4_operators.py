# ============================================
#  1. 算术运算符（做数学计算）
# ============================================
print("=== 1. 算术运算符 ===")

a = 10
b = 3

print(f"{a} + {b} = {a + b}")    # 加法：13
print(f"{a} - {b} = {a - b}")    # 减法：7
print(f"{a} * {b} = {a * b}")    # 乘法：30
print(f"{a} / {b} = {a / b}")    # 除法：3.333...（结果总是浮点数）
print(f"{a} // {b} = {a // b}")   # 整除：3（砍掉小数部分）
print(f"{a} % {b} = {a % b}")     # 取余：1（10除以3余1）
print(f"{a} ** {b} = {a ** b}")   # 幂运算：1000（10的3次方）


# ============================================
#  2. 算术运算符详解
# ============================================
print("\n=== 2. 重要运算符详解 ===")

# ① / 和 // 的区别
print("① / 和 // 的区别：")
print(f"10 / 3 = {10 / 3}")     # 3.333... 普通除法，保留小数
print(f"10 // 3 = {10 // 3}")   # 3        整除，只取整数部分
print(f"10.0 // 3 = {10.0 // 3}")  # 3.0   注意：浮点数整除结果是浮点数

# ② % 取余数（求余数）
print("\n② % 取余数：")
print(f"10 % 3 = {10 % 3}")     # 1  因为 10 = 3*3 + 1
print(f"10 % 2 = {10 % 2}")     # 0  能整除，余数为0
print(f"7 % 4 = {7 % 4}")       # 3  因为 7 = 4*1 + 3
# 判断奇偶数的好方法：x % 2 == 0 是偶数，x % 2 == 1 是奇数

# ③ ** 幂运算（乘方）
print("\n③ ** 幂运算：")
print(f"2 ** 3 = {2 ** 3}")     # 8   2的3次方 = 2*2*2
print(f"5 ** 2 = {5 ** 2}")     # 25  5的平方 = 5*5
print(f"2 ** 10 = {2 ** 10}")   # 1024  2的10次方
print(f"9 ** 0.5 = {9 ** 0.5}") # 3.0  开平方（0.5次方 = 开根号）


# ============================================
#  3. 比较运算符（做判断，返回 True/False）
# ============================================
print("\n=== 3. 比较运算符 ===")

a = 10
b = 3

print(f"{a} > {b}  → {a > b}")     # True   大于
print(f"{a} < {b}  → {a < b}")     # False  小于
print(f"{a} >= {b} → {a >= b}")    # True   大于等于
print(f"{a} <= {b} → {a <= b}")    # False  小于等于
print(f"{a} == {b} → {a == b}")    # False  等于（两个等号！）
print(f"{a} != {b} → {a != b}")    # True   不等于

# ⚠️ 重点：== 和 = 的区别
# =  是赋值：把右边的值放到左边变量里
# == 是比较：判断两边是否相等，返回 True 或 False


# ============================================
#  4. 逻辑运算符（组合多个判断）
# ============================================
print("\n=== 4. 逻辑运算符 ===")

age = 20
has_id = True

# ① and：两边都为 True 才是 True
print("① and（并且）：两边都为真才为真")
print(f"age >= 18 and has_id = {age >= 18 and has_id}")   # True

# ② or：任意一边为 True 就是 True
print("\n② or（或者）：任意一边为真就为真")
is_vip = False
print(f"has_id or is_vip = {has_id or is_vip}")   # True

# ③ not：取反
print("\n③ not（取反）：True变False，False变True")
print(f"not is_vip = {not is_vip}")     # True
print(f"not True = {not True}")         # False


