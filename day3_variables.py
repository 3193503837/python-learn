# ============================================
#  1. 什么是变量？
# ============================================
# 变量就是一个"盒子"，用来装数据。
# 你给盒子起个名字，以后用名字就能找到里面的数据。
#
# 语法：变量名 = 值
# 等号 = 的意思是"把右边的值，放进左边的变量里"

print("=== 1. 什么是变量 ===")

name = "小明"       # 把字符串 "小明" 放进变量 name 里
age = 20            # 把数字 20 放进变量 age 里

print("名字：", name)
print("年龄：", age)

# 变量可以重新赋值（盒子可以装新东西）
age = 21
print("过了一年，年龄变成：", age)

# 也可以用变量给变量赋值
new_age = age
print("new_age 的值：", new_age)


# ============================================
#  2. 变量命名规则
# ============================================
print("\n=== 2. 变量命名规则 ===")

# ✅ 正确的变量名：
user_name = "张三"     # 可以用字母、数字、下划线
age2 = 18              # 可以用数字，但不能开头
_private = "秘密"      # 可以下划线开头

# ❌ 错误的变量名（去掉注释试试，会报错）：
# 2name = "李四"       # 不能数字开头
# user-name = "王五"   # 不能用减号
# user name = "赵六"   # 不能有空格
# class = "一班"       # 不能用Python关键字（保留字）

# 推荐命名风格：蛇形命名法（snake_case）
# 全小写，单词之间用下划线连接
user_age = 25
book_title = "Python入门"
is_student = True

print("命名风格推荐：蛇形命名法 user_name, book_title")


# ============================================
#  3. 基本数据类型
# ============================================
print("\n=== 3. 基本数据类型 ===")

# Python 有4种最基本的数据类型：

# ① 整数（int）：整数，没有小数点
age = 20
year = 2026
print("整数：", age, type(age))   # type() 可以查看数据类型

# ② 浮点数（float）：小数
height = 1.75
weight = 65.5
print("浮点数：", height, type(height))

# ③ 字符串（str）：文字，用引号包起来
name = "小明"
hobby = '编程'
print("字符串：", name, type(name))

# ④ 布尔值（bool）：只有 True 和 False 两种值
is_adult = True
is_student = False
print("布尔值：", is_adult, type(is_adult))


# ============================================
#  4. type() 函数：查看数据类型
# ============================================
print("\n=== 4. type() 查看类型 ===")

print(type(123))        # <class 'int'>
print(type(3.14))       # <class 'float'>
print(type("hello"))    # <class 'str'>
print(type(True))       # <class 'bool'>

# 变量的类型由它装的值决定
x = 100
print("x = 100 时，类型是：", type(x))
x = 3.14
print("x = 3.14 时，类型是：", type(x))
x = "hello"
print("x = 'hello' 时，类型是：", type(x))
# Python 是动态类型语言，变量可以随时换类型


# ============================================
#  5. 类型转换
# ============================================
print("\n=== 5. 类型转换 ===")

# 有时候需要把一种类型转换成另一种类型

# str → int/float
num_str = "123"
num_int = int(num_str)       # 字符串转整数
print("'123' 转整数：", num_int, type(num_int))

float_str = "3.14"
num_float = float(float_str) # 字符串转浮点数
print("'3.14' 转浮点数：", num_float, type(num_float))

# int/float → str
age = 20
age_str = str(age)           # 数字转字符串
print("20 转字符串：", age_str, type(age_str))

# int → float / float → int
print("整数 10 转浮点数：", float(10))
print("浮点数 3.9 转整数：", int(3.9))   # 注意：直接砍掉小数部分，不是四舍五入！

# bool 转换
print("整数转布尔：", bool(1), bool(0))
print("字符串转布尔：", bool("hello"), bool(""))


# ============================================
#  6. 变量的小练习
# ============================================
print("\n=== 6. 小练习：交换两个变量 ===")

a = 10
b = 20
print("交换前：a =", a, "b =", b)

# 方法：用一个临时变量
temp = a
a = b
b = temp
print("交换后：a =", a, "b =", b)

# Python 还可以这样写（后面会学）：
a, b = b, a


