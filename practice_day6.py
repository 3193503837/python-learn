# ---------- 第1题：倒数计时 ----------
# 用 while 循环从 5 倒数到 1
# 每行输出一个数字，最后输出"发射！"
#
# 期望输出：
# 5
# 4
# 3
# 2
# 1
# 发射！

# 你的代码写在这里：
num=5
while num>=1:
    print(num)
    num-=1
print("发射!")

# ---------- 第2题：1到100求和 ----------
# 用 while 循环计算 1+2+3+...+100 的结果
# 提示：用两个变量，一个计数，一个累加
#
# 期望输出：1到100的和是：5050

# 你的代码写在这里：
total=0
num=1
while num<=100:
    total=total+num
    num+=1
print(f"1到100的总和是{total}")





# ---------- 第3题：猜数字游戏 ----------
# 程序生成一个1-100的随机数，用户反复猜
# 猜大了提示"大了"，猜小了提示"小了"，猜对了提示"恭喜，猜了X次"
# 提示：import random  →  num = random.randint(1, 100)
#       用 while True 无限循环，猜对了用 break 跳出

# 你的代码写在这里：
import random
num1=random.randint(1,100)
while True:
    num2 = int(input("请输入数字："))
    if num2<num1:
        print("小了")
    if num2>num1:
        print("大了")
    if num2==num1:
        print("恭喜你，猜对了")
        break


# ---------- 第4题：密码验证（最多3次） ----------
# 让用户输入密码，最多3次机会
# 密码正确（假设密码是"123456"）输出"登录成功"并结束
# 密码错误提示"密码错误，还剩X次机会"
# 3次都错输出"账户已锁定"

# 你的代码写在这里：
num=3
while num>=1:
    key1=123456
    key2=int(input("请输入密码："))
    num-=1
    if key1==key2:
        print("登陆成功")
        break
    else:
        print(f"密码错误，还剩{num}次机会")
else:
    print("账户已锁定")


# ---------- 第5题：九九乘法表（挑战） ----------
# 用嵌套 while 循环输出九九乘法表
# 每行格式：1x1=1
# 提示：外层循环控制行（1到9），内层循环控制列（1到当前行）
#       用 print(..., end="") 控制换行

# 你的代码写在这里：
i=1
while i<=10:
    j=1
    while j<=i:
        print(f"{j}*{i}={i*j}",end="  ")
        j+=1
    print()
    i+=1

