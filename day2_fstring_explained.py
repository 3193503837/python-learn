# ============================================
#  f-string 详解：f 和 {} 分别有什么用？
# ============================================

name = "小明"
age = 20

# ---- 没有 f 的情况 ----
print("=== 没有 f 的情况 ===")
print("我叫{name}，今年{age}岁")
# 输出：我叫{name}，今年{age}岁
#
# 没有 f，{name} 就是普通文字，原样输出
# Python 不知道你想让它替换成变量的值


# ---- 有 f 的情况 ----
print("\n=== 有 f 的情况 ===")
print(f"我叫{name}，今年{age}岁")
# 输出：我叫小明，今年20岁
#
# 有了 f，Python 就知道："哦，这是格式化字符串"
# 然后去找 { } 里的变量，把它们替换成值


# ============================================
#  分角色理解
# ============================================
#
#  f 的作用：开关
#  -------
#  f 就像一个开关，告诉 Python：
#  "注意！这个字符串里有 { } 包起来的变量，
#   你要把它们替换成变量的值！"
#
#  没有 f → { } 就是普通的大括号文字
#  有了 f → { } 里的内容会被当成变量替换
#
#
#  { } 的作用：占位符
#  -------
#  { } 就像一个"空位"或者"占位符"，说：
#  "这里要填一个变量的值！"
#  Python 会把 {变量名} 替换成变量的实际内容
#
# ============================================


# ---- 更多例子对比 ----
print("\n=== 对比例子 ===")

fruit = "苹果"
price = 5

# 没有 f → 原样输出
print("没有f: {fruit}的价格是{price}元")

# 有 f → 替换变量
print(f"有f: {fruit}的价格是{price}元")

# 没有 f + 用逗号（另一种方式）
print("逗号:", fruit, "的价格是", price, "元")


# ---- { } 里面还可以做计算 ----
print("\n=== {} 里可以写表达式 ===")
a = 10
b = 3
print(f"{a} + {b} = {a + b}")       # 输出：10 + 3 = 13
print(f"{a} * {b} = {a * b}")       # 输出：10 * 3 = 30
print(f"a的平方是: {a ** 2}")       # 输出：a的平方是: 100


