# ============================================
#  2. if 语句：如果...就...
# ============================================
print("\n=== 2. if 语句 ===")

age = 20

# 基本语法：
# if 条件:
#     条件成立时执行的代码（必须缩进4个空格）

if age >= 18:
    print("你已经成年了")

# 注意：
# 1. if 后面有空格，然后是条件
# 2. 条件后面有冒号 :
# 3. 下一行必须缩进（4个空格）
# 4. 缩进的代码属于 if 的"管辖范围"


# ============================================
#  3. if / else：如果...就...否则...
# ============================================
print("\n=== 3. if / else ===")

age = 15

if age >= 18:
    print("你已经成年了")
else:
    print("你还未成年")

# else 不需要条件，它是"剩下的所有情况"
# if 和 else 必须对齐（同一缩进层级）


# ============================================
#  4. if / elif / else：多条件判断
# ============================================
print("\n=== 4. if / elif / else ===")

score = 85

# elif = else if 的缩写，表示"否则如果"
# 会从上往下依次判断，一旦某个条件满足，后面的就不看了

if score >= 90:
    print("等级：A（优秀）")
elif score >= 80:
    print("等级：B（良好）")
elif score >= 70:
    print("等级：C（中等）")
elif score >= 60:
    print("等级：D（及格）")
else:
    print("等级：F（不及格）")

# ⚠️ 顺序很重要！
# 如果先写 score >= 60，那 85 也会先匹配到 >= 60，就不会往后判断了
# 所以条件要从严格到宽松排列


# ============================================
#  5. 比较运算符在条件中的使用
# ============================================
print("\n=== 5. 条件中的比较运算符 ===")

temperature = 28

if temperature > 35:
    print("太热了！")
elif temperature > 25:
    print("天气不错，比较暖和")
elif temperature > 10:
    print("有点凉")
else:
    print("太冷了！")


# ============================================
#  6. 逻辑运算符组合条件
# ============================================
print("\n=== 6. 逻辑运算符组合条件 ===")

age = 20
has_ticket = True

# and：两个条件都满足
if age >= 18 and has_ticket:
    print("可以入场看电影")
else:
    print("不能入场")

# or：满足一个就行
is_vip = False
is_student = True

if is_vip or is_student:
    print("享受折扣价！")
else:
    print("原价购买")

# not：取反
raining = False
if not raining:
    print("天气晴朗，可以出门")


# ============================================
#  7. 嵌套 if：if 里面套 if
# ============================================
print("\n=== 7. 嵌套 if ===")

age = 25
has_id = True

if age >= 18:
    print("年龄符合要求")
    if has_id:
        print("有身份证，可以办理")
    else:
        print("缺少身份证，不能办理")
else:
    print("未成年，不能办理")


