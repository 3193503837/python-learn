# ---------- 第4题：列表常用操作 ----------
# 创建空列表：shopping = []
# 依次执行以下操作：
#   1. 添加 "牛奶" 到末尾  → append()
#   2. 添加 "面包" 到末尾  → append()
#   3. 在第 0 个位置插入 "鸡蛋"  → insert(0, "鸡蛋")
#   4. 删除 "面包"  → remove("面包")
#   5. 删除最后一个元素  → pop()
#   6. 输出列表长度  → len()
# 每一步操作后 print() 一下，看看变化

# 你的代码写在这里：
shopping=[]
shopping.append("牛奶")
shopping.append("面包")
shopping.insert(0,"鸡蛋")
shopping.remove("面包")
shopping.pop()
print(len(shopping))
print(shopping)

# ---------- 第5题：遍历列表 ----------
# 创建列表：scores = [85, 92, 78, 60, 95, 88]
# 用 for 循环遍历列表，计算所有分数的总和
# 输出：总分是：XXX，平均分是：XX.X
#
# 提示：total = 0  →  for s in scores: total += s  →  avg = total / len(scores)

# 你的代码写在这里：
total=0
scores=[85,92,78,60,95,88]
for i in scores:
    total+=i
avg=total/len(scores)
print(f"总分是{total}")
print(f"平均分是{avg}")
