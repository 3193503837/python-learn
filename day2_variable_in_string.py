# ============================================
#  为什么输出的是 name 而不是变量的值？
# ============================================

name = "小明"

# ---- 错误写法：变量名写在引号里面 ----
print("错误写法：")
print("hi, name")
# 输出：hi, name
#
# 为什么？因为 name 在引号 "" 里面！
# 引号里的一切都是"普通文字"，Python 会原样输出
# Python 不知道你想让它变成变量的值


# ---- 正确写法1：用逗号分隔（推荐新手用） ----
print("\n正确写法1（逗号）：")
print("hi,", name)
# 输出：hi, 小明
#
# 原理：
#   "hi,"  在引号里 → 是文字，原样输出
#   name   不在引号里 → 是变量，输出它的值
#   逗号 → 自动加空格连接


# ---- 正确写法2：用 + 拼接字符串 ----
print("\n正确写法2（加号）：")
print("hi, " + name)
# 输出：hi, 小明
#
# 原理：+ 把两个字符串接在一起
# 注意："hi, " 后面有个空格，否则会变成 hi,小明


# ---- 正确写法3：f-string（最推荐，最灵活） ----
print("\n正确写法3（f-string）：")
print(f"hi, {name}")
# 输出：hi, 小明
#
# 原理：在引号前加 f，然后用 {变量名} 把变量包起来
# Python 会把 {name} 替换成变量的值
# 这是 Python 最常用、最好用的方式！


# ============================================
#  对比总结
# ============================================

age = 18

print("\n=== 对比表 ===")
print('print("age")   →', "age", "  ← 引号里的是文字，原样输出")
print('print(age)     →', age, "  ← 不在引号里的是变量，输出值")
print('print("我", age, "岁") →', "我", age, "岁", "  ← 逗号分隔，混合用")
print(f'print(f"我{age}岁") → 我{age}岁  ← f-string，最灵活')


